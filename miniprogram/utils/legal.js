const COMPANY = '广州羽美体育发展有限公司'

function head() {
  const lines = [`运营者：${COMPANY}（运营“飞翔羽毛球馆”，以下称“我们”）`]
  if (LEGAL.effectiveDate) lines.push(`生效日期：${LEGAL.effectiveDate}`)
  return lines
}

function contactLines() {
  const lines = [`公司：${COMPANY}`]
  if (LEGAL.contact) lines.push(`联系方式：${LEGAL.contact}`)
  if (LEGAL.address) lines.push(`地址：${LEGAL.address}`)
  if (LEGAL.officer) lines.push(`个人信息保护负责人：${LEGAL.officer}`)
  return lines
}

